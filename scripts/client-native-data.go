//go:build ignore

// Derive native client tables from the current compatibility authority.
// Retire this generator when Rust owns the canonical registry with accepted parity evidence.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"strconv"
	"strings"

	"github.com/channing771/mornlea/packages/client/assets"
	"github.com/channing771/mornlea/packages/shared/core"
	"github.com/channing771/mornlea/packages/shared/physics"
)

const outputPath = "packages/engine/crates/mornlea_client_core/src/runtime_data_generated.rs"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	check := flag.Bool("check", false, "check tracked output without modifying it")
	flag.Parse()
	if flag.NArg() != 0 {
		return fmt.Errorf("unexpected arguments: %v", flag.Args())
	}
	snapshot := assets.NewRegistry().MeshSnapshot()
	if len(snapshot.Blocks) != int(core.BlockIDMax) || len(snapshot.Visibility) != len(snapshot.Blocks)*((len(snapshot.Blocks)+63)/64) {
		return fmt.Errorf("registry does not cover every registered block")
	}
	models := [...]string{"Default", "StandingTorch", "WallTorchPosX", "WallTorchNegX", "WallTorchPosZ", "WallTorchNegZ", "Bed"}
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by go run scripts/client-native-data.go; DO NOT EDIT.")
	fmt.Fprintln(&source, "use mornlea_engine::native::contracts::{Aabb, MeshModel, MeshRegistryEntry};")
	fmt.Fprintf(&source, "pub(super) const MESH_ENTRIES: [MeshRegistryEntry; %d] = [\n", len(snapshot.Blocks))
	for i, block := range snapshot.Blocks {
		if int(block.ID) != i || int(block.Model) >= len(models) {
			return fmt.Errorf("invalid block entry %d", i)
		}
		fmt.Fprintf(&source, "MeshRegistryEntry {id:%d,opaque:%t,emission:%d,fluid_height:%d,light_attenuation:%d,block_top_raw:%d,model:MeshModel::%s,material:[", block.ID, block.Opaque, block.Emission, block.FluidHeight, block.LightAttenuation, block.BlockTopRaw, models[block.Model])
		for _, material := range block.Materials {
			fmt.Fprintf(&source, "%d,", material)
		}
		fmt.Fprintln(&source, "]},")
	}
	fmt.Fprintln(&source, "];")
	fmt.Fprintf(&source, "pub(super) const MESH_VISIBILITY: [u64; %d] = [\n", len(snapshot.Visibility))
	for _, word := range snapshot.Visibility {
		fmt.Fprintf(&source, "%d,\n", word)
	}
	fmt.Fprintln(&source, "];")
	fmt.Fprintln(&source, "const ZERO_BOX: Aabb = Aabb {minimum:[0.0;3],maximum:[0.0;3]};")
	fmt.Fprintf(&source, "pub(super) static COLLISION: [(u8,[Aabb;8]); %d] = [\n", core.BlockIDMax)
	for id := core.AirID; id < core.BlockIDMax; id++ {
		cell := physics.BlockCollisionBoxes(id, true)
		if !cell.Loaded || cell.Count > 8 {
			return fmt.Errorf("invalid collision cell %d", id)
		}
		fmt.Fprintf(&source, "(%d,[", cell.Count)
		for _, box := range cell.Boxes {
			if box == (core.AABB{}) {
				fmt.Fprint(&source, "ZERO_BOX,")
				continue
			}
			fmt.Fprint(&source, "Aabb {minimum:[")
			for _, value := range box.Min {
				fmt.Fprintf(&source, "%s,", rustFloat(value))
			}
			fmt.Fprint(&source, "],maximum:[")
			for _, value := range box.Max {
				fmt.Fprintf(&source, "%s,", rustFloat(value))
			}
			fmt.Fprint(&source, "]},")
		}
		fmt.Fprintln(&source, "]),")
	}
	fmt.Fprintln(&source, "];")
	fmt.Fprintf(&source, "pub(super) const INTERACTION_TARGET: [bool; %d] = [\n", core.BlockIDMax)
	for id := core.AirID; id < core.BlockIDMax; id++ {
		fmt.Fprintf(&source, "%t,\n", core.InteractionTarget(id))
	}
	fmt.Fprintln(&source, "];")
	toolchain, err := os.ReadFile("packages/engine/rust-toolchain.toml")
	if err != nil {
		return err
	}
	var channel string
	for _, line := range strings.Split(string(toolchain), "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "channel = ") {
			channel, err = strconv.Unquote(strings.TrimSpace(strings.SplitN(line, "=", 2)[1]))
			if err != nil {
				return err
			}
		}
	}
	if channel == "" {
		return fmt.Errorf("missing pinned Rust toolchain")
	}
	format := exec.Command("rustup", "run", channel, "rustfmt", "--edition", "2024", "--emit", "stdout")
	format.Stdin = &source
	format.Stderr = os.Stderr
	formatted, err := format.Output()
	if err != nil {
		return fmt.Errorf("format generated Rust: %w", err)
	}
	if *check {
		tracked, err := os.ReadFile(outputPath)
		if err != nil {
			return err
		}
		if !bytes.Equal(tracked, formatted) {
			return fmt.Errorf("%s differs; regenerate with go run scripts/client-native-data.go", outputPath)
		}
		fmt.Fprintf(os.Stderr, "native client data matches: %d entries, %d visibility pairs, %d collision cells\n", len(snapshot.Blocks), len(snapshot.Blocks)*len(snapshot.Blocks), core.BlockIDMax)
		return nil
	}
	_, err = os.Stdout.Write(formatted)
	return err
}

func rustFloat(value float32) string {
	text := strconv.FormatFloat(float64(value), 'f', -1, 32)
	if !strings.Contains(text, ".") {
		text += ".0"
	}
	return text
}
